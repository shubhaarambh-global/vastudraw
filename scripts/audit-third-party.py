from __future__ import annotations

import importlib.metadata
import json
import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / "THIRD_PARTY.generated.md"

blocked_markers = ("AGPL", "SSPL")
python_rows: list[tuple[str, str, str]] = []

for distribution in sorted(
    importlib.metadata.distributions(),
    key=lambda item: (item.metadata.get("Name") or "").lower(),
):
    name = distribution.metadata.get("Name") or "unknown"
    version = distribution.version
    license_value = (
        distribution.metadata.get("License-Expression")
        or distribution.metadata.get("License")
        or "UNKNOWN"
    )
    python_rows.append((name, version, license_value))

for name, version, license_value in python_rows:
    upper = license_value.upper()
    if any(marker in upper for marker in blocked_markers):
        raise SystemExit(
            f"Blocked Python license marker detected: {name} {version} {license_value}"
        )

try:
    completed = subprocess.run(
        ["pnpm", "licenses", "list", "--prod", "--json"],
        cwd=ROOT,
        check=True,
        capture_output=True,
        text=True,
    )
    node_license_json = json.loads(completed.stdout)
except (OSError, subprocess.CalledProcessError, json.JSONDecodeError) as exc:
    node_license_json = {"audit_error": str(exc)}

lines = [
    "# Third-party dependency inventory",
    "",
    "Generated by `python scripts/audit-third-party.py`.",
    "",
    "This is an inventory aid, not legal advice. Review UNKNOWN/custom licenses",
    "before commercial launch.",
    "",
    "## Python environment",
    "",
    "| Package | Version | License metadata |",
    "| --- | --- | --- |",
]
for name, version, license_value in python_rows:
    safe = str(license_value).replace("|", r"\|").replace("\n", " ")
    lines.append(f"| {name} | {version} | {safe} |")

lines.extend(
    [
        "",
        "## Node production dependency license output",
        "",
        "```json",
        json.dumps(node_license_json, indent=2, sort_keys=True),
        "```",
        "",
    ]
)
OUTPUT.write_text("\n".join(lines), encoding="utf-8")
print(f"Wrote: {OUTPUT}")
